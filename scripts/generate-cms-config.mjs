// Generates public/admin/config.yml (Sveltia CMS) from the content in src/content/pages.
// Usage: node scripts/generate-cms-config.mjs [--auth-url https://xxxx.lambda-url.us-east-1.on.aws]
// Re-run after adding a brand directory; the output is committed.
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';
import YAML from 'yaml';

const REPO = process.env.CMS_REPO ?? 'jarretgabel/stereobuyers-astro';
const authArg = process.argv.indexOf('--auth-url');
const AUTH_URL = authArg > -1 ? process.argv[authArg + 1] : process.env.CMS_AUTH_URL;

const CONTENT = 'src/content/pages';
const EQUIPMENT = `${CONTENT}/stereo-equipment-and-components-we-buy`;
// Generated by the migration or derived from the file path at build time; never edited by hand.
const GENERATED = new Set(['url', 'collection', 'source', 'lastmod']);

const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(d, e.name)) : e.name.endsWith('.md') ? [path.join(d, e.name)] : []);
const read = (f) => matter(fs.readFileSync(f, 'utf8')).data;
const mostCommon = (arr) => {
  const c = new Map();
  for (const v of arr.filter(Boolean)) c.set(v, (c.get(v) ?? 0) + 1);
  return [...c.entries()].sort((a, b) => b[1] - a[1])[0]?.[0];
};
const titleCase = (s) => s.replace(/-/g, ' ').replace(/\b\w/g, (m) => m.toUpperCase());

const hidden = (name, def) => ({ name, widget: 'hidden', ...(def !== undefined ? { default: def } : {}) });
const str = (name, label, extra = {}) => ({ name, label, required: false, ...extra });

const productFields = (keys, { layout, brand }) => {
  const known = new Set(['component', 'title', 'seo_title', 'seo_description', 'image', 'type', 'description', 'specs', 'blurb', 'adamSays', 'layout', 'snippet', 'brand']);
  const fields = [
    str('component', 'Product name', { hint: 'For example: Krell KSA-200S. Used for the page URL.' }),
    str('type', 'Component type', { hint: 'For example: Power Amplifier' }),
    { name: 'image', label: 'Image', widget: 'image', required: false, choose_url: false },
    str('description', 'Description', { widget: 'text' }),
    {
      name: 'specs', label: 'Specifications', widget: 'list', required: false, label_singular: 'specification',
      summary: '{{fields.n}}: {{fields.v}}',
      fields: [str('n', 'Name'), str('v', 'Value')],
    },
    str('blurb', 'Short blurb', { widget: 'text' }),
    str('adamSays', 'Adam says', { widget: 'markdown' }),
    str('title', 'Page title (H1)', { hint: 'Leave empty to build it from the product name.' }),
    str('seo_title', 'Search result title (SEO)'),
    str('seo_description', 'Search result description (SEO)', { widget: 'text' }),
    hidden('layout', layout),
    hidden('snippet', 'product'),
    hidden('brand', brand),
  ];
  for (const k of [...keys].sort()) if (!GENERATED.has(k) && !known.has(k)) fields.push(hidden(k));
  return fields;
};

// One collection per brand directory that has product pages.
const brandDirs = fs.readdirSync(EQUIPMENT, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
const productCollections = [];
for (const dir of brandDirs) {
  const files = walk(path.join(EQUIPMENT, dir));
  const fms = files.map(read);
  const products = fms.filter((fm) => fm.snippet === 'product');
  if (!products.length) continue;
  const keys = new Set(fms.flatMap((fm) => Object.keys(fm)));
  const brand = mostCommon(products.map((fm) => fm.brand));
  productCollections.push({
    name: `products-${dir}`,
    label: titleCase(dir),
    label_singular: 'product',
    folder: `${EQUIPMENT}/${dir}`,
    create: true,
    slug: '{{component}}',
    nested: { depth: 100, summary: '{{component}}' },
    meta: { path: { index_file: 'index' } },
    fields: productFields(keys, { layout: mostCommon(products.map((fm) => fm.layout)), brand }),
  });
}
productCollections.sort((a, b) => a.label.localeCompare(b.label));

// Hidden fields keep front matter keys that the editor doesn't expose, so saving an entry never drops them.
const preserve = (folder, fields) => {
  const named = new Set(fields.map((f) => f.name));
  const keys = new Set(walk(folder).flatMap((f) => Object.keys(read(f))));
  return [...fields, ...[...keys].sort().filter((k) => !GENERATED.has(k) && !named.has(k)).map((k) => hidden(k))];
};

